// Opt-in local-stack check. Creates and removes only a randomized test identity.
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import { readdir, readFile, unlink } from 'node:fs/promises'
import { resolve } from 'node:path'
import pg from 'pg'

const origin = 'http://localhost:8080'
if (!process.env.AUTH_SMOKE_DATABASE_URL) throw new Error('Set AUTH_SMOKE_DATABASE_URL for the local development stack')
const databaseURL = new URL(process.env.AUTH_SMOKE_DATABASE_URL)
if (!['localhost', '127.0.0.1'].includes(databaseURL.hostname)) throw new Error('Local databases only')
const pool = new pg.Pool({ connectionString: databaseURL.toString() })
const email = `auth-smoke-${randomUUID()}@example.com`
const inbox = resolve(import.meta.dirname, '../../.auth-mail')
let messageFile
try {
  const response = await fetch(`${origin}/api/auth/sign-in/magic-link`, {
    method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' },
    body: JSON.stringify({ email, callbackURL: '/auth/callback' }),
  })
  assert.equal(response.status, 200, await response.text())
  let url
  for (const name of await readdir(inbox)) {
    const message = JSON.parse(await readFile(resolve(inbox, name), 'utf8'))
    if (message.to === email) { messageFile = resolve(inbox, name); url = message.url; break }
  }
  assert.ok(url, 'development inbox receives the link')
  const verified = await fetch(url, { redirect: 'manual' })
  assert.equal(verified.status, 302)
  const cookie = verified.headers.getSetCookie().map(value => value.split(';')[0]).join('; ')
  assert.match(cookie, /keepfin.session_token=/)
  const me = await fetch(`${origin}/api/v1/user/me`, { headers: { Cookie: cookie } })
  assert.equal(me.status, 200, await me.clone().text())
  const { user } = await me.json()
  assert.equal(user.email, email)
  assert.equal(user.password_hash, undefined)
  assert.equal(user.auth_user_id, undefined)
  const denied = await fetch(`${origin}/api/v1/user/theme`, { method: 'PUT', headers: { Cookie: cookie, Origin: 'https://evil.example', 'Content-Type': 'application/json' }, body: JSON.stringify({ theme: 'dark' }) })
  assert.equal(denied.status, 403)
  const changed = await fetch(`${origin}/api/v1/user/theme`, { method: 'PUT', headers: { Cookie: cookie, Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ theme: 'dark' }) })
  assert.equal(changed.status, 200)
  const again = await fetch(`${origin}/api/v1/user/me`, { headers: { Cookie: cookie } })
  const againUser = (await again.json()).user
  assert.equal(againUser.id, user.id)
  assert.equal(againUser.theme, 'dark')
  const signOut = await fetch(`${origin}/api/auth/sign-out`, { method: 'POST', headers: { Cookie: cookie, Origin: origin, 'Content-Type': 'application/json' }, body: '{}' })
  assert.equal(signOut.status, 200)
  assert.equal((await fetch(`${origin}/api/v1/user/me`, { headers: { Cookie: cookie } })).status, 401)
  assert.notEqual((await fetch(`${origin}/api/v1/user/signin`, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password: 'legacy' }) })).status, 200)
  console.log('PASS: localhost proxy → Magic Link → Go profile/theme → revoke → Go 401; legacy login disabled')
} finally {
  // This unique email was generated by this invocation, never supplied by a user.
  const { rows } = await pool.query('SELECT id FROM auth_user WHERE email = $1', [email])
  for (const { id } of rows) {
    await pool.query('DELETE FROM users WHERE auth_user_id = $1 AND email = $2', [id, email])
    await pool.query('DELETE FROM auth_user WHERE id = $1', [id])
  }
  if (messageFile) await unlink(messageFile)
  await pool.end()
}
